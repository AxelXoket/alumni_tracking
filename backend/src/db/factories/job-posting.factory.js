let counter = 0;

function build(overrides = {}) {
  counter += 1;
  return {
    title: `Software Engineer ${counter}`,
    company: 'Example Tech',
    location: 'Istanbul',
    workMode: 'onsite',
    employmentType: 'full_time',
    description: 'Generated by the job posting factory.',
    ...overrides,
  };
}

async function create(overrides = {}) {
  if (!overrides.userId) throw new Error('jobPostingFactory.create needs a userId');
  return jobPostingModel.create(build(overrides));
}

async function seed({ pool = db.getPool(), log = console.log } = {}) {
  // jobs are posted mostly by alumni and faculty, so prefer those as authors
  const { rows: users } = await pool.query(
    `SELECT id FROM users
      ORDER BY CASE role WHEN 'alumni' THEN 0 WHEN 'faculty' THEN 1 WHEN 'admin' THEN 2 ELSE 3 END, created_at`,
  );
  if (users.length === 0) {
    log('[seed] no users found, skipping job postings');
    return [];
  }

  const inserted = [];
  for (const [index, job] of SAMPLE_JOBS.entries()) {
    const author = users[index % users.length].id;
    const { rowCount } = await pool.query(
      `INSERT INTO job_postings (id, user_id, title, company, location, work_mode, employment_type, description)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
       ON CONFLICT DO NOTHING`,
      [job.id, author, job.title, job.company, job.location, job.workMode, job.employmentType, job.description],
    );
    if (rowCount) inserted.push(job.id);
  }
  log(`[seed] job postings: ${inserted.length} inserted, ${SAMPLE_JOBS.length - inserted.length} already present`);
  return inserted;
}

module.exports = { SAMPLE_JOBS, build, create, seed };
